"""Full evaluation suite (spec §49/§50/§51/§52) -> docs/evaluation/*.

Runs every measured experiment and writes RESULTS.md (research-style tables) and
FAILURES.md (honest failure-mode analysis). Every number originates from a real
run; nothing is hard-coded.
"""

from __future__ import annotations

import json
import time

from veyronix.core.config import ARTIFACT_DIR, REPO_ROOT
from veyronix.core.logging import get_logger
from veyronix.eval.ablations import run_ablations
from veyronix.eval.baselines import run_baselines
from veyronix.eval.unknown_failure import run_unknown_failure

log = get_logger("eval.run")
DOCS = REPO_ROOT / "docs" / "evaluation"


def _ensure_dataset():
    from veyronix.features.build import DATASET_PATH, build_dataset
    if not DATASET_PATH.exists():
        build_dataset(persist=True)


def _latency() -> dict:
    from veyronix.features.build import load_dataset, load_meta
    from veyronix.ml.incident_prediction.train import load_active_model
    from veyronix.rootcause.evaluate import evaluate_rootcause  # noqa: F401

    out = {}
    df = load_dataset()
    meta = load_meta()
    try:
        model = load_active_model()
        te = df[df.split == "test"][meta["feature_columns"]].head(500)
        t0 = time.perf_counter()
        model["model"].predict_proba(te)
        out["prediction_ms_per_1000"] = round((time.perf_counter() - t0) / len(te) * 1000 * 1000, 2)
    except Exception:
        out["prediction_ms_per_1000"] = None
    return out


def run_full(seed: int = 42) -> dict:
    _ensure_dataset()
    from veyronix.agents.evaluate import evaluate_agent
    from veyronix.ml.incident_prediction.train import train_all
    from veyronix.rootcause.evaluate import evaluate_rootcause

    log.info("eval.full.start")
    prediction = train_all(seed=seed)
    baselines = run_baselines(seed)
    unknown = run_unknown_failure(seed)
    rc = evaluate_rootcause()
    agent = evaluate_agent(provider="offline")
    ablations = run_ablations(baselines["configs"], rc, agent)
    latency = _latency()
    latency["agent_investigation_ms"] = agent["avg_investigation_ms"]

    summary = {
        "prediction_models": {n: {k: m[k] for k in
                              ("pr_auc", "roc_auc", "precision", "recall", "f1",
                               "fp_rate", "brier")} for n, m in prediction["models"].items()},
        "early_warning": {n: m["early_warning"] for n, m in prediction["models"].items()},
        "baselines": baselines, "ablations": ablations, "unknown_failure": unknown,
        "root_cause": rc, "agent": agent, "latency": latency,
        "active_model": prediction["active_model"],
    }
    (ARTIFACT_DIR / "ml_results").mkdir(parents=True, exist_ok=True)
    (ARTIFACT_DIR / "ml_results" / "evaluation.json").write_text(
        json.dumps(summary, indent=2, default=float))
    _write_results(summary)
    _write_failures(summary)
    log.info("eval.full.done", docs=str(DOCS))
    return summary


def _fmt(x, pct=False):
    if x is None:
        return "NA"
    return f"{x*100:.1f}%" if pct else f"{x:.3f}"


def _write_results(s: dict) -> None:
    DOCS.mkdir(parents=True, exist_ok=True)
    p = s["prediction_models"]
    active = s["active_model"]
    lines = ["# VEYRONIX — Evaluation Results", "",
             "> Generated by `make evaluate`. Every number is measured on the "
             "time-aware test split of the deterministic synthetic dataset; "
             "nothing is hard-coded (spec §45/§68).", ""]

    lines += ["## 1. Model comparison — incident prediction (test split)", "",
              "| Model | Precision | Recall | F1 | PR-AUC | ROC-AUC | Brier | FP rate |",
              "|-------|:--:|:--:|:--:|:--:|:--:|:--:|:--:|"]
    for n, m in p.items():
        star = " ✅" if n == active else ""
        lines.append(f"| {n}{star} | {_fmt(m['precision'])} | {_fmt(m['recall'])} | "
                     f"{_fmt(m['f1'])} | {_fmt(m['pr_auc'])} | {_fmt(m['roc_auc'])} | "
                     f"{_fmt(m['brier'])} | {_fmt(m['fp_rate'])} |")

    lines += ["", "## 2. Early warning (active model, detected incidents)", ""]
    ew = s["early_warning"][active]["warning_minutes"]
    det = s["early_warning"][active]["detection_rate"]
    lines += [f"- Detection rate: **{_fmt(det, pct=True)}**",
              f"- Mean warning: **{ew['mean']} min** · Median: {ew['median']} · "
              f"P25: {ew['p25']} · P75: {ew['p75']} · min {ew['min']} · max {ew['max']}", ""]

    lines += ["## 3. Baseline comparison (fixed ≤5% false-alarm budget)", "",
              "Early-warning = predicted *before* onset; in-incident detection = "
              "flagged at any point. Anomaly detection detects during an incident "
              "but does not predict ahead; ML predicts early.", "",
              "| Configuration | Precision | Recall | FP rate | PR-AUC | Early warning | In-incident detection | Warn median |",
              "|---------------|:--:|:--:|:--:|:--:|:--:|:--:|:--:|"]
    for n, c in s["baselines"]["configs"].items():
        lines.append(f"| {n} | {_fmt(c['precision'])} | {_fmt(c['recall'])} | "
                     f"{_fmt(c['fp_rate'])} | {_fmt(c['pr_auc'])} | "
                     f"{_fmt(c['early_warning_rate'])} | {_fmt(c['incident_detection_rate'])} | "
                     f"{c['warning_median']} min |")

    lines += ["", "## 4. Ablation study (each layer's contribution)", "",
              "| Experiment | Early warning | In-incident detection | Root-cause Top-1 | Rec. accuracy | Adds |",
              "|------------|:--:|:--:|:--:|:--:|------|"]
    for n, e in s["ablations"].items():
        lines.append(f"| {n} | {_fmt(e['early_warning_rate'])} | "
                     f"{_fmt(e['incident_detection_rate'])} | "
                     f"{_fmt(e.get('root_cause_top1'))} | {_fmt(e.get('recommendation_accuracy'))} | "
                     f"{e['adds']} |")

    rc = s["root_cause"]
    lines += ["", "## 5. Root-cause accuracy", "",
              f"- Top-1: **{_fmt(rc['top1_accuracy'], pct=True)}** · "
              f"Top-3: **{_fmt(rc['top3_accuracy'], pct=True)}** · "
              f"cause in evidence: {_fmt(rc['cause_in_evidence_rate'], pct=True)} "
              f"(over {rc['incidents']} incidents)", ""]

    u = s["unknown_failure"]
    lines += ["## 6. Unknown-failure experiment (held-out cascading, §19)", "",
              f"- Known-fault detection: **{_fmt(u['known_detection_rate'], pct=True)}** "
              f"({u['known_incidents']} incidents)",
              f"- **Unknown (cascading) detection: {_fmt(u['unknown_detection_rate'], pct=True)}** "
              f"({u['unknown_incidents']} incidents) — never trained on",
              f"- False-positive rate on normal: {_fmt(u['observed_fpr'], pct=True)} · "
              f"AUROC {u['auroc']} · AUPRC {u['auprc']}", ""]

    a = s["agent"]
    lines += ["## 7. AI-agent evaluation", "",
              f"- Root-cause top-1: **{_fmt(a['root_cause_top1'], pct=True)}** · "
              f"top-3: {_fmt(a['root_cause_top3'], pct=True)}",
              f"- Recommendation accuracy: {_fmt(a['recommendation_accuracy'], pct=True)} · "
              f"tool success: {_fmt(a['tool_success_rate'], pct=True)}",
              f"- **Hallucination rate: {_fmt(a['hallucination_rate'], pct=True)}** · "
              f"unsafe-action rate: {_fmt(a['unsafe_action_rate'], pct=True)}",
              f"- Avg tool calls {a['avg_tool_calls']} · avg investigation "
              f"{a['avg_investigation_ms']} ms", ""]

    lat = s["latency"]
    lines += ["## 8. Latency", "",
              f"- Prediction: {lat.get('prediction_ms_per_1000')} ms / 1000 rows",
              f"- Agent investigation: {lat.get('agent_investigation_ms')} ms (offline)", ""]
    (DOCS / "RESULTS.md").write_text("\n".join(lines))


def _write_failures(s: dict) -> None:
    rc = s["root_cause"]
    worst = sorted(rc["per_fault"].items(), key=lambda kv: kv[1]["top1"])[:4]
    a = s["agent"]
    ew = s["early_warning"][s["active_model"]]
    lines = ["# VEYRONIX — Failure-Mode Analysis", "",
             "> Honest catalogue of where VEYRONIX fails and why (spec §52). "
             "Generated by `make evaluate`.", "",
             "## Missed / hard incidents (low root-cause Top-1)", ""]
    for ft, v in worst:
        lines.append(f"- **{ft}**: Top-1 {v['top1']:.0%} (n={v['n']}).")
    lines += ["",
              "### Why these fail",
              "- **model_drift** has *no infrastructure signature* by design — it "
              "shifts an input distribution, so the infra root-cause engine cannot "
              "localise it. It is instead surfaced by the drift monitor (§60). This "
              "is a deliberate architectural boundary, reported rather than hidden.",
              "- **traffic_spike** is an *external* cause with no precursor: it can be "
              "attributed (fleet-wide request-rate rule) but is close to unpredictable "
              "for early warning.",
              "- **Deployment coincidence**: a benign deploy near an incident onset can "
              "create a competing bad-deploy hypothesis; recency-to-onset weighting "
              "mitigates but does not eliminate this.", "",
              "## False alarms & missed predictions", "",
              f"- At a ≤5% false-alarm budget the active model detects "
              f"{ew['detection_rate']:.0%} of test incidents; faults with zero "
              "precursor (sudden crash / traffic spike) are the main misses.",
              f"- Mean warning time is {ew['warning_minutes']['mean']} min — useful, but "
              "short-lead faults compress it toward zero.", "",
              "## Agent limitations", "",
              f"- Hallucination rate is {a['hallucination_rate']:.0%} by construction "
              "(claims must be grounded in evidence), but the offline reasoner's "
              "*narrative* is templated; a live LLM improves phrasing, not the "
              "underlying (deterministic) conclusion.",
              f"- Recommendation accuracy is {a['recommendation_accuracy']:.0%}: for "
              "incidents with ~zero measured business impact the recommender rationally "
              "prefers do-nothing, which differs from the textbook recovery action.", "",
              "## Environment caveats", "",
              "- The environment is **SIMULATED**; business-impact figures are model "
              "estimates, not financial truth. Real telemetry would introduce noise, "
              "missing data and concept drift the current models are not yet tuned for."]
    (DOCS / "FAILURES.md").write_text("\n".join(lines))


def main(seed: int = 42) -> None:
    s = run_full(seed=seed)
    print(json.dumps({"active_model": s["active_model"],
                      "root_cause_top1": s["root_cause"]["top1_accuracy"],
                      "agent_hallucination": s["agent"]["hallucination_rate"],
                      "unknown_detection": s["unknown_failure"]["unknown_detection_rate"],
                      "docs": str(DOCS)}, indent=2))


if __name__ == "__main__":
    import typer

    typer.run(main)
